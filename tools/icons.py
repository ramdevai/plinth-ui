#!/usr/bin/env python3
"""Frame UI icon tooling (maintenance only, apps never need it).

Icons are Lucide (ISC licence, https://lucide.dev), curated into icons.list (category: names).
  python3 tools/icons.py build            icons.list -> icons.svg (sprite) + icons.json (manifest) + pages/icons.html
  python3 tools/icons.py add NAME [CAT]   add an icon to icons.list and rebuild
  python3 tools/icons.py subset FILE...   print a sprite containing only icons referenced as #i-name in FILEs (for production)
Lucide source is fetched on demand with `npm pack lucide-static` into tools/.cache (gitignored).
"""
import json, re, subprocess, sys, tarfile, html, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / 'tools' / '.cache'
LIST = ROOT / 'icons.list'

def source():
    pkg = CACHE / 'package'
    if not (pkg / 'icons').exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        subprocess.run(['npm', 'pack', 'lucide-static'], cwd=CACHE, check=True, capture_output=True)
        tgz = next(CACHE.glob('lucide-static-*.tgz'))
        with tarfile.open(tgz) as t: t.extractall(CACHE, filter='data')
    return pkg

def read_list():
    cats, cur = {}, None
    for line in LIST.read_text().splitlines():
        line = line.split('#')[0].rstrip()
        if not line.strip(): continue
        if line.endswith(':'): cur = line[:-1].strip(); cats[cur] = []
        else: cats[cur] += line.split()
    return cats

def inner(svg):
    m = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S)
    body = re.sub(r'\s+', ' ', m.group(1)).strip()
    return re.sub(r'>\s+<', '><', body)

def build():
    pkg = source(); tags = json.loads((pkg / 'tags.json').read_text()); cats = read_list()
    seen, items, missing = set(), [], []
    for cat, names in cats.items():
        for n in names:
            if n in seen: continue
            f = pkg / 'icons' / f'{n}.svg'
            if not f.exists(): missing.append(n); continue
            seen.add(n); items.append((n, cat, inner(f.read_text())))
    sprite = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">', '<!-- Lucide icons (ISC) — generated by tools/icons.py from icons.list. Use: <svg class="f-i"><use href="#i-NAME"/></svg> -->']
    sprite += [f'<symbol id="i-{n}" viewBox="0 0 24 24">{b}</symbol>' for n, c, b in items] + ['</svg>']
    (ROOT / 'icons.svg').write_text('\n'.join(sprite) + '\n')
    manifest = [{'name': n, 'category': c, 'tags': tags.get(n, [])[:8], 'use': f'<svg class="f-i"><use href="#i-{n}"/></svg>'} for n, c, _ in items]
    (ROOT / 'icons.json').write_text(json.dumps({'source': 'Lucide (ISC) https://lucide.dev', 'count': len(manifest), 'sizes': {'default': 18, 'sm': 15, 'lg': 22}, 'icons': manifest}, indent=1) + '\n')
    page(manifest, list(cats))
    print(f'built {len(items)} icons, sprite {(ROOT/"icons.svg").stat().st_size//1024} KB' + (f'; MISSING: {missing}' if missing else ''))
    return missing

def page(manifest, cats):
    chips = '<button class="f-chip" aria-pressed="true" data-value="">All <span class="f-chip__n">%d</span></button>' % len(manifest)
    for c in cats:
        n = sum(1 for m in manifest if m['category'] == c)
        if n: chips += f'<button class="f-chip" aria-pressed="false" data-value="{html.escape(c)}">{html.escape(c)} <span class="f-chip__n">{n}</span></button>'
    tiles = ''
    for m in manifest:
        use = html.escape(m['use'], quote=True)
        text = html.escape(' '.join([m['name'].replace('-', ' '), m['category']] + m['tags']).lower())
        tiles += (f'<button class="f-icontile" data-name="{m["name"]}" data-cat="{html.escape(m["category"])}" data-f-text="{text}" data-f-copy="{use}" aria-label="Copy {m["name"]}">'
                  f'<svg class="f-i"><use href="#i-{m["name"]}"/></svg><span>{m["name"]}</span></button>\n')
    out = f'''<!-- ICONS — GENERATED by tools/icons.py from icons.list. Do not edit by hand. -->
<section data-screen="icons" hidden class="f-stack" style="gap:16px">
  <div class="f-head">
    <div><h1 class="f-h1">Icons</h1><p class="f-subtitle"><span data-f-filter-count="#iconGrid">{len(manifest)}</span> icons · <a href="https://lucide.dev" target="_blank" rel="noopener" style="text-decoration:underline">Lucide</a> (ISC licence), 24px grid, 2px round stroke · click an icon to copy its markup</p></div>
    <div class="f-head__actions">
      <div class="f-seg" data-f-var-group aria-label="Size"><button aria-pressed="false" data-f-var="#iconGrid|--s|15px">15</button><button aria-pressed="true" data-f-var="#iconGrid|--s|18px">18</button><button aria-pressed="false" data-f-var="#iconGrid|--s|22px">22</button><button aria-pressed="false" data-f-var="#iconGrid|--s|32px">32</button></div>
      <div class="f-seg" data-f-var-group aria-label="Stroke"><button aria-pressed="false" data-f-var="#iconGrid|--sw|1.25">Light</button><button aria-pressed="true" data-f-var="#iconGrid|--sw|1.6">Regular</button><button aria-pressed="false" data-f-var="#iconGrid|--sw|2.1">Bold</button></div>
    </div>
  </div>
  <div class="f-toolbar">
    <label class="f-search" style="width:min(320px,100%)"><svg class="f-i"><use href="#i-search"/></svg><input data-f-filter="#iconGrid" placeholder="Search icons, e.g. download, user, chart…" aria-label="Search icons"></label>
    <div class="f-chips" data-f-chips data-f-filter-cat="#iconGrid" style="flex-wrap:wrap">{chips}</div>
  </div>
  <div class="f-card">
    <div class="f-icongrid" id="iconGrid">
{tiles}    </div>
    <div class="f-empty" data-f-filter-empty="#iconGrid" hidden><span class="f-empty__icon"><svg class="f-i f-i--lg"><use href="#i-search"/></svg></span><h3>No icons match</h3><p>Try a broader word. Need one that isn't here? Run <code class="f-mono">python3 tools/icons.py add NAME</code> (any name from lucide.dev).</p></div>
  </div>
  <div class="f-card"><h3 class="f-card__title">Using icons</h3>
    <pre class="f-code">&lt;svg class="f-i"&gt;&lt;use href="#i-search"/&gt;&lt;/svg&gt;          &lt;!-- 18px --&gt;
&lt;svg class="f-i f-i--sm"&gt;&lt;use href="#i-search"/&gt;&lt;/svg&gt;    &lt;!-- 15px --&gt;
&lt;svg class="f-i f-i--lg"&gt;&lt;use href="#i-search"/&gt;&lt;/svg&gt;    &lt;!-- 22px --&gt;</pre>
    <p class="f-muted" style="margin:0">Icons take the text colour (<code class="f-mono">currentColor</code>). Inline <code class="f-mono">icons.svg</code> once near the top of <code class="f-mono">&lt;body&gt;</code>. For production, <code class="f-mono">python3 tools/icons.py subset index.html …</code> prints a sprite with only the icons you use. Icon-only buttons need an <code class="f-mono">aria-label</code>; decorative icons next to text need nothing.</p></div>
</section>
'''
    (ROOT / 'pages' / 'icons.html').write_text(out)

def add(name, cat='Misc'):
    cats = read_list()
    if any(name in v for v in cats.values()): print(name, 'already present'); return
    if not (source() / 'icons' / f'{name}.svg').exists(): sys.exit(f'No Lucide icon named {name!r} (see https://lucide.dev/icons)')
    text = LIST.read_text().rstrip('\n').split('\n'); out, done = [], False
    for i, l in enumerate(text):
        out.append(l)
    # append to the category block (or create it)
    lines = LIST.read_text().split('\n'); idx = None
    for i, l in enumerate(lines):
        if l.strip() == f'{cat}:': idx = i
    if idx is None: lines += ['', f'{cat}:', f'  {name}']
    else:
        j = idx + 1
        while j < len(lines) and lines[j].startswith('  '): j += 1
        lines.insert(j, f'  {name}')
    LIST.write_text('\n'.join(lines)); build()

def subset(files):
    used = sorted({m for f in files for m in re.findall(r'#i-([a-z0-9-]+)', pathlib.Path(f).read_text())})
    sprite = (ROOT / 'icons.svg').read_text()
    syms = dict(re.findall(r'<symbol id="i-([a-z0-9-]+)"(.*?)</symbol>', sprite, re.S))
    miss = [u for u in used if u not in syms]
    print('<svg xmlns="http://www.w3.org/2000/svg" style="display:none">')
    for u in used:
        if u in syms: print(f'<symbol id="i-{u}"{syms[u]}</symbol>')
    print('</svg>')
    if miss: print('<!-- missing from icons.svg:', ' '.join(miss), '-->', file=sys.stderr)

if __name__ == '__main__':
    a = sys.argv[1:]
    if not a or a[0] == 'build': sys.exit(1 if build() else 0)
    elif a[0] == 'add': add(a[1], a[2] if len(a) > 2 else 'Misc')
    elif a[0] == 'subset': subset(a[1:])
    else: print(__doc__)
