# --- accessibility patch: daisyUI's own *-content colours sometimes miss WCAG AA (4.5:1). We fix those and record them. ---
import math
def lch(v):
    v = v.strip()
    m = re.match(r'#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$', v)
    if m:
        h = m.group(1); h = ''.join(c * 2 for c in h) if len(h) == 3 else h
        r, g, b = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
        f = lambda c: c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4
        r, g, b = f(r), f(g), f(b)
        l_ = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3); m_ = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3); s_ = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
        L = 0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_; a = 1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_; bb = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_
        return L, math.hypot(a, bb), math.degrees(math.atan2(bb, a)) % 360
    m = re.match(r'oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)', v)
    if not m: return None
    return float(m.group(1)) / (100 if m.group(2) else 1), float(m.group(3)), float(m.group(4))
def fmt(L, C, H): return f'oklch({L * 100:.1f}% {C:.3f} {H:.1f})'
def _oklch(v):
    x = lch(v)
    if x is None: return None
    L, C, h = x[0], x[1], math.radians(x[2])
    a, b = C * math.cos(h), C * math.sin(h)
    l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3; m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3; s_ = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_; g = -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_; bl = -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_
    return 0.2126 * max(r, 0) + 0.7152 * max(g, 0) + 0.0722 * max(bl, 0)
def _cr(x, y):
    a, b = _oklch(x), _oklch(y)
    return None if a is None or b is None else (max(a, b) + .05) / (min(a, b) + .05)
def a11y_patch(d):
    fixed = []
    for role in ('primary', 'accent', 'secondary', 'neutral', 'info', 'success', 'warning', 'error'):
        bg, fg = d.get(f'--color-{role}'), d.get(f'--color-{role}-content')
        c = _cr(bg, fg) if bg and fg else None
        if c is not None and c < 4.5:
            best = max(('oklch(100% 0 0)', 'oklch(0% 0 0)'), key=lambda x: _cr(bg, x))
            if _cr(bg, best) >= 4.5: d[f'--color-{role}-content'] = best; fixed.append(f'{role} {c:.1f}->{_cr(bg, best):.1f}')
    return fixed

WHITE, BLACK = 'oklch(100% 0 0)', 'oklch(0% 0 0)'
ROLES = ('primary', 'secondary', 'accent', 'info', 'success', 'warning', 'error')
def best_content(bg):
    return max((WHITE, BLACK), key=lambda x: _cr(bg, x))

def counterpart(d, scheme):
    """The other mode of a theme, derived from its own colours: same hues, inverted surfaces, brand colours kept legible."""
    b2 = lch(d['--color-base-200']); hue = b2[2] if b2[1] > .004 else (lch(d['--color-primary'])[2])
    c = min(b2[1], .03) if b2[1] > .004 else 0.0
    o = {}
    if scheme == 'light':          # -> dark
        o['color-scheme'] = 'dark'
        bases = ((.24, '--color-base-100'), (.20, '--color-base-200'), (.31, '--color-base-300'))
        content = fmt(.95, .01 if c else 0, hue)
    else:                          # -> light
        o['color-scheme'] = 'light'
        bases = ((.99, '--color-base-100'), (.96, '--color-base-200'), (.91, '--color-base-300'))
        content = fmt(.22, .02 if c else 0, hue)
    for L, k in bases: o[k] = fmt(L, c, hue)
    o['--color-base-content'] = content
    for r in ROLES:
        L, C, H = lch(d[f'--color-{r}'])
        L2 = max(L, .68) if scheme == 'light' else min(L, .58)
        o[f'--color-{r}'] = fmt(L2, C, H); o[f'--color-{r}-content'] = best_content(o[f'--color-{r}'])
    nL, nC, nH = lch(d['--color-neutral'])
    o['--color-neutral'] = fmt(.30 if scheme == 'light' else .28, min(nC, .03), nH)
    o['--color-neutral-content'] = fmt(.93 if scheme == 'light' else .96, 0, nH)
    return o

def preset_full(p):
    h = p['hue']
    return {'color-scheme': 'light', '--color-base-100': 'oklch(100% 0 0)', '--color-base-200': f'oklch(95.3% .008 {h})', '--color-base-300': f'oklch(90% .01 {h})', '--color-base-content': f'oklch(20% .01 {h})',
            '--color-primary': p['primary'], '--color-primary-content': p['on'], '--color-secondary': 'oklch(60% .16 285)', '--color-secondary-content': '#fff',
            '--color-accent': p['accent'], '--color-accent-content': p['on_accent'], '--color-neutral': f'oklch(25% .01 {h})', '--color-neutral-content': '#fff',
            '--color-info': 'oklch(60% .15 255)', '--color-info-content': '#fff', '--color-success': 'oklch(62% .15 150)', '--color-success-content': '#fff',
            '--color-warning': 'oklch(77% .15 75)', '--color-warning-content': 'oklch(20% .05 75)', '--color-error': 'oklch(60% .19 30)', '--color-error-content': '#fff',
            '--radius-box': '1rem', '--radius-field': '0.625rem', '--radius-selector': '999px'}

def body_of(d):
    return ' '.join(f'{k}: {d[k]};' for k in ['color-scheme'] + [k for k in KEYS if k != 'color-scheme'] if k in d)

def build():
    pkg = source(); ver = json.loads((pkg / 'package.json').read_text())['version']
    th = {k: v for k, v in parse(pkg).items() if k in KEEP}
    css = [f'/* Frame UI themes (generated by tools/themes.py, do not hand-edit; client colours go in theme.css).\n   Frame presets first, then {len(th)} daisyUI {ver} themes (MIT, https://daisyui.com).\n   Where a theme own -content colour missed WCAG AA (4.5:1) it was swapped for white/black; see a11y_patched in themes.json.\n   Apply with <html data-theme="name">. Load AFTER frame.css. */\n']
    man = []; allt = {}
    for n, p in PRESETS.items():
        css.append(f'[data-theme="{n}"] {{ --neutral-hue: {p["hue"]}; --color-primary: {p["primary"]}; --color-primary-content: {p["on"]}; --color-accent: {p["accent"]}; --color-accent-content: {p["on_accent"]}; }}')
        man.append(dict(name=n, source='frame', scheme='light', modes=['light', 'dark'], primary=p['primary'], accent=p['accent'], base='oklch(1 0 0)'))
        allt[n] = ('light', preset_full(p))
    css.append('')
    for n, d in th.items():
        patched = a11y_patch(d)
        body = ' '.join(f'{k}: {d[k]};' for k in KEYS if k in d)
        css.append(f'[data-theme="{n}"] {{ {body} }}')
        allt[n] = (d.get('color-scheme', 'light'), d)
        man.append(dict(name=n, source='daisyui', scheme=d.get('color-scheme', 'light'), modes=['light', 'dark'], primary=d['--color-primary'], accent=d['--color-accent'], base=d['--color-base-100'], **({'a11y_patched': patched} if patched else {})))
    css.append('\n/* ---- the other mode of every theme: <html data-theme="x" data-mode="dark|light"> (generated from each theme own colours) ---- */')
    for n, (scheme, d) in allt.items():
        other = 'dark' if scheme == 'light' else 'light'
        css.append(f'[data-theme="{n}"][data-mode="{other}"] {{ {body_of(counterpart(d, scheme))} }}')
    out = ROOT / 'themes'; out.mkdir(exist_ok=True)
    for f in out.glob('*.css'): f.unlink()
    for n, (scheme, d) in allt.items():
        other = 'dark' if scheme == 'light' else 'light'
        base = f'[data-theme="{n}"] {{ {body_of(d)} }}' if n not in PRESETS else next(l for l in css if l.startswith(f'[data-theme="{n}"] '))
        (out / f'{n}.css').write_text(f'/* Frame UI theme "{n}" ({scheme}); data-mode="{other}" gives its {other} version. Link this ONE file after frame.css.{"" if n in PRESETS else " Colours from daisyUI (MIT, (c) Pouya Saadeghi); see LICENSES/daisyui-MIT.txt."} */\n{base}\n[data-theme="{n}"][data-mode="{other}"] {{ {body_of(counterpart(d, scheme))} }}\n')
    (ROOT / 'themes.css').write_text('\n'.join(css) + '\n')
    (ROOT / 'pages' / 'themes.html').write_text(page(man, ver))
    (ROOT / 'themes.json').write_text(json.dumps(dict(daisyui=ver, count=len(man), themes=man), indent=1))
    print(f'themes.css: {len(man)} themes ({len(th)} daisyUI {ver}); {(ROOT/"themes.css").stat().st_size//1024} KB')

if __name__ == '__main__':
    if sys.argv[1:2] == ['build']: build()
    else: print(__doc__)
