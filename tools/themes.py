# daisyUI themes we ship: only ones that pass the axe + contrast sweep in both modes (see README). Add a name here and rebuild to ship another.
KEEP = ['corporate', 'business', 'nord', 'dracula', 'cupcake']

def source():
    pkg = CACHE / 'package'
    if not (pkg / 'theme').exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        subprocess.run(['npm', 'pack', 'daisyui'], cwd=CACHE, check=True, capture_output=True)
        tgz = next(CACHE.glob('daisyui-*.tgz'))
        with tarfile.open(tgz) as t: t.extractall(CACHE, filter='data')
    return pkg

def parse(pkg):
    out = {}
    for f in sorted((pkg / 'theme').glob('*.css')):
        txt = f.read_text()
        m = re.search(r'\[data-theme="?([\w-]+)"?\]\s*\{(.*?)\}', txt, re.S)
        if not m: continue
        decl = {k: v.strip() for k, v in re.findall(r'(--?[\w-]+|color-scheme)\s*:\s*([^;]+);', m.group(2))}
        out[m.group(1)] = decl
    return out

KEYS = ['color-scheme','--color-base-100','--color-base-200','--color-base-300','--color-base-content','--color-primary','--color-primary-content','--color-secondary','--color-secondary-content','--color-accent','--color-accent-content','--color-neutral','--color-neutral-content','--color-info','--color-info-content','--color-success','--color-success-content','--color-warning','--color-warning-content','--color-error','--color-error-content','--radius-selector','--radius-field','--radius-box','--size-selector','--size-field','--border','--depth','--noise']

