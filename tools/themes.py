#!/usr/bin/env python3
"""Frame UI theme tooling (maintenance only; apps never need it).

  python3 tools/themes.py build   -> themes.css (all KEEP themes, for the gallery) + themes/NAME.css (ONE theme, both modes: what apps link) + themes.json

daisyUI (MIT, https://daisyui.com) themes are fetched on demand with `npm pack daisyui` into tools/.cache.
Per-client colours do NOT go in themes.css: copy theme.example.css to theme.css and edit that.
"""
import json, re, subprocess, sys, tarfile, pathlib, html
ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / 'tools' / '.cache' / 'daisy'

# Frame presets: primary, accent and a neutral hue are all a client needs. Other tokens come from the defaults in frame.css.
